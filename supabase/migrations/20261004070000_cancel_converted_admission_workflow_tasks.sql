-- SCHOOL OS — ADMISSION CONVERSION TASK CLOSURE
-- Migration: Cancel obsolete workflow-generated admission
--            review tasks when an admission is converted.
-- ============================================================

-- ------------------------------------------------------------
-- CANCEL ACTIVE WORKFLOW TASKS FOR A CONVERTED ADMISSION
-- ------------------------------------------------------------

create or replace function public.cancel_converted_student_admission_workflow_tasks(
    p_organization_id uuid,
    p_admission_id uuid
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    /*
     * A converted admission has reached a terminal business outcome.
     *
     * Any still-open or in-progress task generated by that admission's
     * workflow is therefore obsolete. It is cancelled rather than
     * completed or deleted:
     *
     *   open/in_progress -> cancelled
     *
     * This preserves the task record and its audit history while removing
     * the stale operational exception from the active queue.
     */

    update public.tasks t
    set
        status = 'cancelled',
        updated_at = now()
    where t.status in ('open', 'in_progress')
      and exists (
          select 1
          from public.workflow_task_links wtl
          join public.workflow_instances wi
            on wi.organization_id = wtl.organization_id
           and wi.id = wtl.workflow_instance_id
          where wtl.organization_id = p_organization_id
            and wtl.task_id = t.id
            and wi.organization_id = p_organization_id
            and wi.subject_type = 'student_admission_request'
            and wi.subject_id = p_admission_id
      );
end;
$$;

revoke all on function
    public.cancel_converted_student_admission_workflow_tasks(uuid, uuid)
from public;

grant execute on function
    public.cancel_converted_student_admission_workflow_tasks(uuid, uuid)
to authenticated;

comment on function
    public.cancel_converted_student_admission_workflow_tasks(uuid, uuid)
is
    'Cancels still-open workflow-generated admission tasks when the admission has been converted into a Student. Preserves task history and removes obsolete operational exceptions.';

-- ------------------------------------------------------------
-- FUTURE CONVERSIONS
-- ------------------------------------------------------------

drop trigger if exists
    cancel_converted_student_admission_workflow_tasks
on public.student_admission_requests;

create or replace function public.trigger_cancel_converted_student_admission_workflow_tasks()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    perform public.cancel_converted_student_admission_workflow_tasks(
        new.organization_id,
        new.id
    );

    return new;
end;
$$;

revoke all on function
    public.trigger_cancel_converted_student_admission_workflow_tasks()
from public;

grant execute on function
    public.trigger_cancel_converted_student_admission_workflow_tasks()
to authenticated;

create trigger
    cancel_converted_student_admission_workflow_tasks
after update of status
on public.student_admission_requests
for each row
when (
    new.status = 'converted'
    and old.status is distinct from 'converted'
)
execute function
    public.trigger_cancel_converted_student_admission_workflow_tasks();

-- ------------------------------------------------------------
-- RECONCILE EXISTING CONVERTED ADMISSIONS
-- ------------------------------------------------------------

do $$
declare
    v_row record;
begin
    for v_row in
        select
            sar.organization_id,
            sar.id
        from public.student_admission_requests sar
        where sar.status = 'converted'
    loop
        perform public.cancel_converted_student_admission_workflow_tasks(
            v_row.organization_id,
            v_row.id
        );
    end loop;
end;
$$;

-- ------------------------------------------------------------
-- DOCUMENT THE OPERATING RULE
-- ------------------------------------------------------------

comment on trigger
    cancel_converted_student_admission_workflow_tasks
on public.student_admission_requests
is
    'When an admission is converted into a Student, obsolete open or in-progress workflow-generated admission tasks are cancelled rather than completed or deleted.';

